export const isDate = x => x instanceof Date;
export const isRegExp = x => x instanceof RegExp;
export const isMap = x => x instanceof Map;
export const isSet = x => x instanceof Set;
export const isWeakMap = x => x instanceof WeakMap;
export const isWeakSet = x => x instanceof WeakSet;
export const isPromise = x => x instanceof Promise;
export const isNativeError = x => x instanceof Error;
export const isArrayBuffer = x => x instanceof ArrayBuffer;
export const isSharedArrayBuffer = x => x instanceof SharedArrayBuffer;
export const isAnyArrayBuffer = x => isArrayBuffer(x) || isSharedArrayBuffer(x);
export const isArrayBufferView = x => ArrayBuffer.isView(x);
export const isDataView = x => x instanceof DataView;
export const isTypedArray = x => ArrayBuffer.isView(x) && !(x instanceof DataView);
export const isAsyncFunction = x => typeof x === 'function' && /^Async/.test(Object.prototype.toString.call(x).slice(8, -1));
export const isGeneratorFunction = x => typeof x === 'function' && /GeneratorFunction\]$/.test(Object.prototype.toString.call(x));
export const isNumberObject = x => x instanceof Number;
export const isStringObject = x => x instanceof String;
export const isBooleanObject = x => x instanceof Boolean;
export const isBigIntObject = x => typeof x === 'object' && x instanceof BigInt;
export const isSymbolObject = x => typeof x === 'object' && x instanceof Symbol;
export const isBoxedPrimitive = x => isNumberObject(x) || isStringObject(x) || isBooleanObject(x) || isBigIntObject(x) || isSymbolObject(x);
export const isArgumentsObject = x => Object.prototype.toString.call(x) === '[object Arguments]';
